-- 0024_skill_library.sql（skill 库 · owner 2026-10-30 裁定「独立于其他 agent」）
--
-- 背景：本地扫描登记的 skill 都指着**别的 agent 的目录**（~/.claude/skills 等）。
-- 那个 agent 升级、卸载、被清理时，skill 就没了 —— 台账里只剩一条指向死路径的记录，
-- 且没有任何地方留有内容副本（455 条里 38 条已是这样）。
--
-- 落点：**备份一份到 OpenVibe 自己的目录**（~/.openvibe/skills/<name>/），
-- 台账记下这份副本在哪（library_dir）。副本与原件各自独立：
--  - 原件还在 → 备份保证「agent 走了内容还在」；
--  - 原件没了 → 备份是唯一的可恢复来源。
--
-- ⚠️ 为什么是「加列」而不是「加表」：
--   备份是**每条 skill 至多一份**的从属关系（一条 skill ↔ 一个副本目录），
--   不存在「一条 skill 多份备份」或「备份独立于 skill 存在」的形态 ⇒ 一列足够。
--   加表会引入第二个需要 join 与级联的实体，而那份实体没有独立语义。
--
-- ⚠️ 存量条目一律留空（NULL = 未备份）：
--   迁移不去扫磁盘、不复制文件 —— 迁移必须是纯 schema 变更。
--   备份由用户显式触发（skill 页的「备份到库」动作）。
ALTER TABLE skills ADD COLUMN library_dir TEXT;
